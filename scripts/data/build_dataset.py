"""Build the complete mixed [0,8]^2 dataset DIRECTLY from the per-maze
processed sources (data/processed/maze2d_{maze}).  No intermediate on-disk copy.

Pipeline (one script):
    maze2d_{umaze,medium,large} (per-maze map/traj/offline-IRIS labels)
      -> scale/pad into [0,8]^2 target frame
      -> shared normalization across all mazes
      -> per-maze resampled occupancy + SDF
      -> merged train/val/test
      -> data/processed/mixed/

Prereq: per-maze ellipse labels already generated by scripts/data/04_generate_ellipse_labels.py.

Usage:
    python scripts/data/build_mixed_dataset.py --config configs/config.yaml
"""
import os, sys, numpy as np
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
import scipy.ndimage as ndimage
from src.utils.config import load_config
from src.datasets.normalization import state_normalizer, load_normalization, save_normalization

DEST = "data/processed/mixed"
TARGET = (0.0, 8.0, 0.0, 8.0)
RES = 10.0
SHAPE = (80, 80)
SPLITS = ["train", "val", "test"]


def scale_offsets(extent):
    x0, x1, y0, y1 = extent
    s = min((TARGET[1] - TARGET[0]) / (x1 - x0), (TARGET[3] - TARGET[2]) / (y1 - y0))
    scalex = s * (x1 - x0)
    scaley = s * (y1 - y0)
    offx = (TARGET[1] - TARGET[0] - scalex) / 2.0 + TARGET[0]
    offy = (TARGET[3] - TARGET[2] - scaley) / 2.0 + TARGET[2]
    return s, offx, offy


def world_to_target(p, s, offx, offy):
    p = np.asarray(p, dtype=np.float64)
    return np.stack([s * p[..., 0] + offx, s * p[..., 1] + offy], axis=-1)


def build_target_occ(occ, extent, gres, s, offx, offy):
    ny, nx = SHAPE
    x0, x1, y0, y1 = extent
    X = (np.arange(nx) + 0.5) / RES
    Y = (np.arange(ny) + 0.5) / RES
    XX, YY = np.meshgrid(X, Y, indexing="xy")
    oX = (XX - offx) / s
    oY = (YY - offy) / s
    px = np.round((oX - x0) * gres - 0.5).astype(int)
    py = np.round((oY - y0) * gres - 0.5).astype(int)
    valid = (px >= 0) & (px < occ.shape[1]) & (py >= 0) & (py < occ.shape[0])
    out = np.ones((ny, nx), dtype=np.uint8)  # out-of-range -> wall
    px_c = np.clip(px, 0, occ.shape[1] - 1)
    py_c = np.clip(py, 0, occ.shape[0] - 1)
    out[valid] = occ[py_c[valid], px_c[valid]]
    return out


def build_sdf_from_occ(occ):
    """Signed distance field from a binary occupancy (1=wall).  Free>0, wall<0."""
    wall = occ == 1
    free = ~wall
    d_free = ndimage.distance_transform_edt(free)
    d_wall = ndimage.distance_transform_edt(wall)
    return (d_free - d_wall).astype(np.float32)


def unnorm_pos(cond, norm):
    x = np.asarray(cond, dtype=np.float64).reshape(-1, 2)
    mins = norm.mins[2:4]; maxs = norm.maxs[2:4]; eps = norm.eps
    return ((x + 1.0) / 2.0 * (maxs - mins + eps) + mins).reshape(cond.shape)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/config.yaml")
    args = ap.parse_args()
    cfg = load_config(args.config)

    # ---- 1) convert every maze's source data into the target frame (in memory) ----
    converted = {}               # name -> {'occ': target_occ, 'splits': {...}}
    all_world = []
    for spec in cfg["mazes"]:
        name = spec["name"]; src = spec["processed_dir"]
        extent = tuple(spec["extent"]); gres = float(spec["global_res"])
        s, offx, offy = scale_offsets(extent)
        occ = np.load(os.path.join(src, "map", "occupancy.npy"))
        occt = build_target_occ(occ, extent, gres, s, offx, offy)
        normm, _ = load_normalization(os.path.join(src, "normalization.json"))

        splits = {}
        for split in SPLITS:
            sd = os.path.join(src, split)
            traj = np.load(os.path.join(sd, "trajectories.npy"))
            cond = np.load(os.path.join(sd, "conditions.npy"))
            ep = np.load(os.path.join(sd, "ellipse_params.npy"))
            eq = np.load(os.path.join(sd, "ellipse_Q.npy"))
            ev = np.load(os.path.join(sd, "ellipse_valid.npy"))
            # full 6-dim state to world, then scale all dims by s; positions add off
            world = normm.unnormalize(np.asarray(traj, dtype=np.float64))
            world_s = world * s
            world_s[..., 2:4] += np.array([offx, offy])
            # conditions (normalized pos) -> world -> target
            cw = world_to_target(unnorm_pos(cond, normm), s, offx, offy)
            # ellipse: center -> target, radii * s, theta unchanged; Q / s^2
            ep_t = ep.copy()
            ep_t[..., 0:2] = world_to_target(ep[..., 0:2], s, offx, offy)
            ep_t[..., 2:4] = ep[..., 2:4] * s
            eq_t = eq / (s * s)
            splits[split] = dict(traj_world=world_s, cond_world=cw,
                                 ep=ep_t, eq=eq_t, ev=ev)
            all_world.append(world_s)
        converted[name] = dict(occ=occt, splits=splits)
        print(f"[convert] {name}: s={s:.4f} offx={offx:.4f} offy={offy:.4f} "
              f"occ={occt.shape} splits={ {k: v['traj_world'].shape[0] for k, v in splits.items()} }")

    # ---- 2) shared normalization across all mazes ----
    all_world = np.concatenate(all_world, axis=0)
    norm = state_normalizer(all_world)
    os.makedirs(DEST, exist_ok=True)
    save_normalization(os.path.join(DEST, "normalization.json"), norm)

    # ---- 3) per-maze target maps + SDF ----
    os.makedirs(os.path.join(DEST, "maps"), exist_ok=True)
    for name, c in converted.items():
        occ = c["occ"]; sdf = build_sdf_from_occ(occ)
        np.save(os.path.join(DEST, "maps", f"{name}.npy"), occ)
        np.save(os.path.join(DEST, "maps", f"{name}_sdf.npy"), sdf)

    # ---- 4) merge splits ----
    for split in SPLITS:
        traj = []; cond = []; ep = []; eq = []; ev = []; mid = []
        for idx, (name, c) in enumerate(converted.items()):
            d = c["splits"][split]
            traj.append(d["traj_world"]); cond.append(d["cond_world"])
            ep.append(d["ep"]); eq.append(d["eq"]); ev.append(d["ev"])
            mid.append(np.full(len(d["traj_world"]), idx, dtype=np.int64))
        traj = np.concatenate(traj, 0); cond = np.concatenate(cond, 0)
        ep = np.concatenate(ep, 0); eq = np.concatenate(eq, 0)
        ev = np.concatenate(ev, 0); mid = np.concatenate(mid, 0)
        norm_traj = norm.normalize(traj).astype(np.float32)
        mins = norm.mins[2:4]; maxs = norm.maxs[2:4]; eps = norm.eps
        cc = (cond - mins) / (maxs - mins + eps)
        norm_cond = (2.0 * cc - 1.0).astype(np.float32)
        out = os.path.join(DEST, split)
        os.makedirs(out, exist_ok=True)
        np.save(os.path.join(out, "trajectories.npy"), norm_traj)
        np.save(os.path.join(out, "conditions.npy"), norm_cond)
        np.save(os.path.join(out, "ellipse_params.npy"), ep.astype(np.float32))
        np.save(os.path.join(out, "ellipse_Q.npy"), eq.astype(np.float32))
        np.save(os.path.join(out, "ellipse_valid.npy"), ev)
        np.save(os.path.join(out, "maze_id.npy"), mid)
        print(f"[data] {split}: n={len(traj)} {[int((mid == i).sum()) for i in range(3)]}")

    print("DONE mixed dataset at", DEST)


if __name__ == "__main__":
    main()
